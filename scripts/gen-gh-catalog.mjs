// Writes the Grasshopper component catalog from the JavaScript registry, so the .gha and the editor
// can never disagree about which nodes exist, what their ports and parameters are called, or what
// their defaults are. Run after changing a node definition:
//   node scripts/gen-gh-catalog.mjs
//
// Output (committed):
//   dotnet/Swalloop.Grasshopper/Catalog.g.cs      the catalog as one JSON string
//   dotnet/Swalloop.Grasshopper/Components.g.cs   one small component class per generic node type
//
// Node types with their own behaviour are written by hand (LoopStart, LoopEnd, Inspect, Readout,
// Viewer); they still appear in the catalog, which is what the template builder reads.
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { registry } from '../src/core/registry.js';
import '../src/packs/index.js';

const root = fileURLToPath(new URL('../', import.meta.url));
const OUT = root + 'dotnet/Swalloop.Grasshopper/';

// Hand-written components: the generator must not emit a class for these.
const CUSTOM = new Set(['loopEnd', 'inspect', 'readout', 'viewer']);
// Friendlier names where the editor's title carries decoration.
const TITLES = { loopStart: 'Loop Start', loopEnd: 'Loop End' };
const EXPOSURE = { Migration: 'primary', Site: 'secondary', Physics: 'tertiary', Analysis: 'quarternary', Utility: 'quinary', Input: 'senary', Output: 'septenary', Math: 'quinary' };

// A stable GUID per node type: the same on every machine and every build.
const guidFor = (id) => {
  const h = createHash('md5').update(`swalloop:node:${id}`).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20, 32)}`;
};
const nick = (title) => title.replace(/[^A-Za-z0-9]/g, '').slice(0, 8);

const catalog = [];
for (const [id, def] of Object.entries(registry.nodeTypes)) {
  const title = TITLES[id] ?? def.title.replace(/^.*·\s*/, '');
  catalog.push({
    id,
    title,
    nick: nick(title),
    category: def.category,
    exposure: EXPOSURE[def.category] ?? 'quinary',
    pack: def.pack ?? 'core',
    guid: guidFor(id),
    custom: CUSTOM.has(id),
    inputs: def.inputs.map((p) => ({ id: p.id, label: p.label, type: p.type, optional: Boolean(p.optional) })),
    params: def.params.map((p) => ({
      id: p.id,
      label: p.label,
      default: p.default,
      options: p.select ?? null,
      min: p.min ?? null,
      max: p.max ?? null,
    })),
    outputs: def.outputs.map((p) => ({ id: p.id, label: p.label, type: p.type })),
  });
}
catalog.sort((a, b) => a.id.localeCompare(b.id));

const json = JSON.stringify(catalog).replace(/"/g, '""');
writeFileSync(
  OUT + 'Catalog.g.cs',
  `// <auto-generated> by scripts/gen-gh-catalog.mjs from the JavaScript node registry. Do not edit. </auto-generated>
namespace Swalloop.GH
{
    internal static class CatalogJson
    {
        public const string Json = @"${json}";
    }
}
`,
);

const classes = catalog
  .filter((n) => !n.custom)
  .map((n) => `    [NodeType("${n.id}")]\n    public sealed class C_${n.id} : NodeComponent\n    {\n        public C_${n.id}() : base("${n.id}") { }\n        public override Guid ComponentGuid => new Guid("${n.guid}");\n    }\n`)
  .join('\n');
writeFileSync(
  OUT + 'Components.g.cs',
  `// <auto-generated> by scripts/gen-gh-catalog.mjs from the JavaScript node registry. Do not edit. </auto-generated>
using System;

namespace Swalloop.GH
{
${classes}}
`,
);

console.log(`catalog: ${catalog.length} node types, ${catalog.filter((n) => !n.custom).length} generated components, ${catalog.filter((n) => n.custom).length} hand-written`);
