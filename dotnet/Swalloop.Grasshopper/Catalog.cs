using System;
using System.Collections.Generic;
using System.Linq;
using System.Reflection;
using Grasshopper.Kernel;
using Swalloop.Core;

namespace Swalloop.GH
{
    /// <summary>Marks a component class with the engine node type it stands for.</summary>
    [AttributeUsage(AttributeTargets.Class)]
    public sealed class NodeTypeAttribute : Attribute
    {
        public string Id { get; }
        public NodeTypeAttribute(string id) { Id = id; }
    }

    public sealed class PortMeta
    {
        public string Id, Label, Type;
        public bool Optional;
    }

    public sealed class ParamMeta
    {
        public string Id, Label;
        public object Default;
        public string[] Options; // null for a number
        public double? Min, Max;
        public bool IsSelect { get { return Options != null; } }
    }

    /// <summary>Everything the plugin needs to know about one node type. Generated from the JavaScript registry.</summary>
    public sealed class NodeMeta
    {
        public string Id, Title, Nick, Category, Pack;
        public GH_Exposure Exposure;
        public Guid Guid;
        public bool Custom;
        public PortMeta[] Inputs, Outputs;
        public ParamMeta[] Params;

        /// <summary>Input parameters on the component: the node's inputs, then its numeric and select parameters.</summary>
        public int InputCount { get { return Inputs.Length + Params.Length; } }
        public string InputId(int k) { return k < Inputs.Length ? Inputs[k].Id : Params[k - Inputs.Length].Id; }
        public int InputIndex(string id)
        {
            for (var k = 0; k < InputCount; k++) if (InputId(k) == id) return k;
            return -1;
        }
        public int OutputIndex(string id)
        {
            for (var k = 0; k < Outputs.Length; k++) if (Outputs[k].Id == id) return k;
            return -1;
        }
    }

    /// <summary>
    /// The component catalog: which node types exist and how they look in Grasshopper. The data is
    /// generated by scripts/gen-gh-catalog.mjs from the editor's own registry, so ports, parameter
    /// names and defaults cannot drift between the editor and the plugin.
    /// </summary>
    public static class Catalog
    {
        /// <summary>The engine registry every component and every loop evaluates with.</summary>
        public static readonly Registry Engine = Registry.CreateDefault();

        public static readonly IReadOnlyDictionary<string, NodeMeta> Nodes = Load();

        private static Dictionary<string, NodeMeta> Load()
        {
            var list = (List<object>)MiniJson.Parse(CatalogJson.Json);
            var map = new Dictionary<string, NodeMeta>();
            foreach (Dictionary<string, object> d in list)
            {
                var m = new NodeMeta
                {
                    Id = (string)d["id"],
                    Title = (string)d["title"],
                    Nick = (string)d["nick"],
                    Category = (string)d["category"],
                    Pack = (string)d["pack"],
                    Guid = new Guid((string)d["guid"]),
                    Custom = d["custom"] is bool b && b,
                    Exposure = ParseExposure((string)d["exposure"]),
                    Inputs = ((List<object>)d["inputs"]).Select(o => Port((Dictionary<string, object>)o)).ToArray(),
                    Outputs = ((List<object>)d["outputs"]).Select(o => Port((Dictionary<string, object>)o)).ToArray(),
                    Params = ((List<object>)d["params"]).Select(o => Param((Dictionary<string, object>)o)).ToArray(),
                };
                map[m.Id] = m;
            }
            return map;
        }

        private static PortMeta Port(Dictionary<string, object> d)
        {
            return new PortMeta
            {
                Id = (string)d["id"],
                Label = (string)d["label"],
                Type = (string)d["type"],
                Optional = d.TryGetValue("optional", out var o) && o is bool b && b,
            };
        }

        private static ParamMeta Param(Dictionary<string, object> d)
        {
            return new ParamMeta
            {
                Id = (string)d["id"],
                Label = (string)d["label"],
                Default = d["default"],
                Options = d["options"] is List<object> opts ? opts.Select(x => (string)x).ToArray() : null,
                Min = d["min"] is double mn ? mn : (double?)null,
                Max = d["max"] is double mx ? mx : (double?)null,
            };
        }

        private static GH_Exposure ParseExposure(string s)
        {
            return Enum.TryParse<GH_Exposure>(s, out var e) ? e : GH_Exposure.secondary;
        }

        public static NodeMeta For(string id)
        {
            if (!Nodes.TryGetValue(id, out var m)) throw new InvalidOperationException("Unknown Swalloop node type \"" + id + "\".");
            return m;
        }

        public static NodeMeta ForComponent(Type t)
        {
            var a = t.GetCustomAttribute<NodeTypeAttribute>();
            if (a == null) throw new InvalidOperationException(t.Name + " has no [NodeType] attribute.");
            return For(a.Id);
        }

        public static string Describe(NodeMeta m)
        {
            var parts = new List<string>();
            foreach (var p in m.Params.Where(p => p.IsSelect)) parts.Add(p.Label + ": " + string.Join(" / ", p.Options));
            return m.Title + " (" + m.Category + "). " + (parts.Count > 0 ? string.Join(". ", parts) + "." : "");
        }
    }
}
